#!/bin/bash
# Browser-capability eval runner for the consult skill.
#
# Runs the authenticated and unauthenticated browser probes on every
# installed harness (codex, agy, claude, kiro) and regenerates _profile.md —
# the routing source for browser-automation lanes. Rerun after any harness
# CLI, extension, or permission-grant change; if a lane newly passes a probe
# (e.g. agy gaining an authenticated path), the profile flips it into that
# pool automatically.
#
# Cheap models only. Lanes run in parallel; probes within a lane run
# serially. A lane that errors or times out records as FAIL with its output
# tail as evidence. Raw outputs are kept in a temp dir printed at the end.
set -u
cd "$(dirname "$0")"

AUTH_PROMPT=$(cat authenticated-probe.md)
UNAUTH_PROMPT=$(cat unauthenticated-probe.md)
OUT=$(mktemp -d "${TMPDIR:-/tmp}/browser-eval.XXXXXX")

TO=""
command -v gtimeout >/dev/null 2>&1 && TO="gtimeout 240"

# All lanes run with cwd in $OUT: Playwright MCP (and kin) drop session
# artifacts (.playwright-mcp/page-*.yml) into cwd — they belong in the temp
# dir, not the repo.
run_codex() { # $1 prompt
  # Browser recipe from references/codex.md: NO --ignore-user-config (it
  # strips the MCP servers that carry the browser runtime).
  $TO codex exec --ephemeral --skip-git-repo-check -C "$OUT" \
    -m gpt-5.6-luna -c 'model_reasoning_effort="low"' \
    -s read-only "$1" </dev/null 2>&1
}
run_agy() { # $1 prompt
  # Flag order matters: --print "<prompt>" must come last.
  (cd "$OUT" && $TO agy --model gemini-3.7-flash-low --mode plan --sandbox \
    --print-timeout 200s --print "$1" </dev/null 2>&1)
}
run_claude() { # $1 prompt
  # Browser recipe from references/claude.md: --chrome enables the extension
  # integration (off by default in -p); default permission mode, because
  # plan mode blocks the browser tools; prompt must precede the variadic
  # --allowedTools flag or it swallows the prompt.
  (cd "$OUT" && $TO claude -p --chrome --model sonnet "$1" \
    --allowedTools "mcp__claude-in-chrome" </dev/null 2>&1)
}
run_kiro() { # $1 prompt
  # references/kiro.md is an unverified stub; revisit when validated.
  echo "KIRO-STUB: non-interactive invocation not yet validated (references/kiro.md)"
}

lane_worker() { # $1 lane name
  local lane="$1"
  "run_${lane}" "$AUTH_PROMPT"   > "$OUT/${lane}.auth.txt"
  "run_${lane}" "$UNAUTH_PROMPT" > "$OUT/${lane}.unauth.txt"
}

# Harnesses that echo the probe prompt into their transcript (codex exec
# does) would false-match on the format examples; those lines contain
# literal <placeholders>, so matches containing '<' are discarded.
grade() { # $1 file, $2 pass marker, $3 extra required string ("" = none)
  local f="$1" marker="$2" extra="$3"
  if grep "$marker" "$f" | grep -qv '<' \
     && { [ -z "$extra" ] || grep -q "$extra" "$f"; }; then
    echo "PASS"
  else
    echo "FAIL"
  fi
}

evidence() { # $1 file, $2 pass marker, $3 fail marker
  local line
  line=$(grep -E "$2|$3" "$1" | grep -v '<' | tail -1)
  [ -z "$line" ] && line=$(tail -1 "$1")
  echo "${line:0:100}"
}

LANES=""
for lane in codex agy claude kiro; do
  cli="$lane"; [ "$lane" = kiro ] && cli="kiro-cli"
  if command -v "$cli" >/dev/null 2>&1; then
    LANES="$LANES $lane"
    lane_worker "$lane" &
  else
    echo "not installed" > "$OUT/${lane}.skip"
  fi
done
wait

{
  echo "# Browser lane profile"
  echo
  echo "GENERATED by run.sh — do not hand-edit. Regenerate after any harness"
  echo "CLI, browser-extension, or permission-grant change."
  echo
  echo "generated: $(date '+%Y-%m-%d %H:%M %Z')"
  echo "versions: codex $(codex --version 2>/dev/null | awk '{print $2}') · agy $(agy --version 2>/dev/null) · claude $(claude --version 2>/dev/null | awk '{print $1}')"
  echo
  echo "| lane | authenticated (user's live browser) | unauthenticated (disposable browser) |"
  echo "|------|-------------------------------------|--------------------------------------|"
  for lane in codex agy claude kiro; do
    if [ -f "$OUT/${lane}.skip" ]; then
      echo "| $lane | — not installed | — not installed |"
      continue
    fi
    a=$(grade "$OUT/${lane}.auth.txt" "AUTH-BROWSER-OK" "")
    u=$(grade "$OUT/${lane}.unauth.txt" "UNAUTH-BROWSER-OK" "Example Domain")
    ae=$(evidence "$OUT/${lane}.auth.txt" "AUTH-BROWSER-OK" "AUTH-BROWSER-FAIL")
    ue=$(evidence "$OUT/${lane}.unauth.txt" "UNAUTH-BROWSER-OK" "UNAUTH-BROWSER-FAIL")
    echo "| $lane | $a — $ae | $u — $ue |"
  done
  echo
  echo "Routing rule: authenticated browser work goes only to lanes with"
  echo "authenticated=PASS. Unauthenticated work may use any PASS lane,"
  echo "ranked per routing.md task tiers. Recipes: references/<lane>.md."
} > _profile.md

echo "wrote _profile.md; raw outputs in $OUT"
